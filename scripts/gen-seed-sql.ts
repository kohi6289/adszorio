// Generates supabase/seed.sql from src/data/seed.ts so the DB and the offline fallback never drift.
// Run: pnpm seed:gen
import { writeFileSync } from "node:fs";
import { legalPages } from "../src/data/legal.ts";
import { categories, currencies, faqs, packages, platforms, services, siteSettings } from "../src/data/seed.ts";

type Row = Record<string, unknown>;

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
    return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replaceAll("'", "''")}'`;
};

const insert = (table: string, rows: Row[], conflict: string) => {
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflict}) do nothing;\n`;
};

const sql = [
  "-- GENERATED by scripts/gen-seed-sql.ts from src/data/seed.ts. Do not edit by hand.",
  "-- No testimonials and no stats are seeded: those must be real.",
  insert("platforms", platforms as unknown as Row[], "id"),
  insert("categories", categories as unknown as Row[], "id"),
  insert("services", services as unknown as Row[], "id"),
  insert("packages", packages as unknown as Row[], "id"),
  insert("currencies", currencies as unknown as Row[], "code"),
  insert("faqs", faqs as unknown as Row[], "id"),
  insert("legal_pages", legalPages.map((l) => ({ ...l, version: 1, published_at: "2026-11-07T00:00:00Z" })), "slug"),
  insert("site_settings", [{ id: 1, data: siteSettings, private: { notification_emails: [siteSettings.contact.email], first_order_max_usd: 250 } }], "id"),
].join("\n");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql");
